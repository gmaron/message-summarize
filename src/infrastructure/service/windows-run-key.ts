import { win32 } from 'node:path'
import type {
  ServiceDefinition,
  ServiceFailure,
  ServiceInstallation,
  ServiceInstaller,
  ServiceRemoval,
  ServiceStatus,
} from '../../application/ports/service-installer.js'
import { err, ok, type Result } from '../../domain/result.js'
import { assertSingleLine, firstLine, type ServiceHost } from './host.js'

export const RUN_KEY = 'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Run'
export const RUN_VALUE = 'message-summarize'
export const LAUNCHER_NAME = 'daemon-launcher.ps1'

/** The first pause after a crash, and the longest one (RNF-07: back within 30 s). */
const FIRST_DELAY_SECONDS = 5
const MAX_DELAY_SECONDS = 20
/** A daemon that ran at least this long was healthy: the next crash starts from the first pause again. */
const HEALTHY_SECONDS = 60

/** PowerShell reads the typographic quotes as quotes too, so all of them are doubled. */
const psQuote = (text: string): string => {
  assertSingleLine(text)
  return `'${text.replace(/['‘’‚‛]/g, (quote) => quote + quote)}'`
}

/**
 * The script that keeps the daemon alive. Windows has no `Restart=` for a login entry, so this is the whole of it: run
 * the daemon, and if it ends with an error, wait (5 s, 10 s, 20 s, then 20 s; back to 5 s after a run of a minute or
 * more) and run it again. A clean exit (code 0) ends the loop. Its own output is discarded: the daemon keeps its log
 * file in the data directory. The loop also ends when this file is gone, which is how `service uninstall` stops it from
 * bringing the daemon back.
 */
export function launcherScript(definition: ServiceDefinition): string {
  const [program, ...args] = definition.command
  if (program === undefined) throw new Error('service definition has no command')
  const lines = [
    '# Generated by "msum service install". It starts the daemon and starts it again after a crash.',
    "$ErrorActionPreference = 'Continue'",
    ...Object.entries(definition.env).map(([name, value]) => {
      if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new Error('service definition has an invalid variable name')
      return `$env:${name} = ${psQuote(value)}`
    }),
    `$delay = ${FIRST_DELAY_SECONDS}`,
    'while ($true) {',
    '  if (-not (Test-Path -LiteralPath $PSCommandPath)) { exit 0 }',
    '  $started = Get-Date',
    `  & ${psQuote(program)} ${args.map(psQuote).join(' ')} *> $null`,
    '  if ($LASTEXITCODE -eq 0) { exit 0 }',
    `  if (((Get-Date) - $started).TotalSeconds -ge ${HEALTHY_SECONDS}) { $delay = ${FIRST_DELAY_SECONDS} }`,
    '  Start-Sleep -Seconds $delay',
    `  $delay = [Math]::Min($delay * 2, ${MAX_DELAY_SECONDS})`,
    '}',
    '',
  ]
  // A BOM, because Windows PowerShell 5.1 reads a script without one as ANSI and would mangle a user name with accents.
  return `﻿${lines.join('\r\n')}`
}

/**
 * The value of the Run key: PowerShell, hidden, running the launcher. `-ExecutionPolicy Bypass` applies to this one
 * process only and is needed because the policy of many machines refuses scripts; no administrator rights are needed.
 */
export function runCommandLine(launcherPath: string): string {
  assertSingleLine(launcherPath)
  return `powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -WindowStyle Hidden -File "${launcherPath}"`
}

/**
 * Windows: a value in `HKCU\Software\Microsoft\Windows\CurrentVersion\Run`, which starts the launcher at the user's
 * login. Chosen over a Windows service and over the Task Scheduler because it needs no administrator rights and
 * touches no scheduler. It is written with `reg.exe`, so there is no native module. The registration takes effect at
 * the next login; the installer does not start a second daemon next to one the user may already be running.
 */
export class WindowsRunKeyInstaller implements ServiceInstaller {
  constructor(private readonly host: ServiceHost) {}

  private launcherPath(dataDir: string): string {
    return win32.join(dataDir, LAUNCHER_NAME)
  }

  private query() {
    return this.host.runner.run('reg', ['query', RUN_KEY, '/v', RUN_VALUE])
  }

  async install(definition: ServiceDefinition): Promise<Result<ServiceInstallation, ServiceFailure>> {
    const launcher = this.launcherPath(definition.dataDir)
    const script = launcherScript(definition)
    const line = runCommandLine(launcher)
    const location = `${RUN_KEY}\\${RUN_VALUE}`
    const [scriptBefore, registered] = await Promise.all([this.host.files.read(launcher), this.query()])
    if (scriptBefore === script && registered.code === 0 && registered.stdout.includes(line)) {
      return ok({ location, changed: false, hints: ['startAtNextLogin'] })
    }
    await this.host.files.write(launcher, script, 0o600)
    const added = await this.host.runner.run('reg', ['add', RUN_KEY, '/v', RUN_VALUE, '/t', 'REG_SZ', '/d', line, '/f'])
    if (added.code !== 0) return err({ step: 'reg add', detail: firstLine(added) })
    return ok({ location, changed: true, hints: ['startAtNextLogin'] })
  }

  async uninstall(): Promise<Result<ServiceRemoval, ServiceFailure>> {
    const location = `${RUN_KEY}\\${RUN_VALUE}`
    const registered = await this.query()
    if (registered.code === 0) {
      const deleted = await this.host.runner.run('reg', ['delete', RUN_KEY, '/v', RUN_VALUE, '/f'])
      if (deleted.code !== 0) return err({ step: 'reg delete', detail: firstLine(deleted) })
    }
    // The launcher is the one the Run value names (the data directory may have changed since), else the usual place.
    const registeredLauncher = /-File "([^"]+)"/.exec(registered.stdout)?.[1]
    const launcher =
      registeredLauncher !== undefined && win32.basename(registeredLauncher) === LAUNCHER_NAME
        ? registeredLauncher
        : this.launcherPath(this.host.dataDir)
    // Without its script the loop of a running launcher ends when the daemon it started does.
    const hadScript = await this.host.files.remove(launcher)
    const removed = registered.code === 0 || hadScript
    return ok({ removed, location, hints: removed ? ['stopRunningDaemon'] : [] })
  }

  async status(): Promise<ServiceStatus> {
    const registered = await this.query()
    return { installed: registered.code === 0, location: `${RUN_KEY}\\${RUN_VALUE}`, running: null }
  }
}
